import { createInterface } from "node:readline";
import { Command } from "commander";
import { config } from "#/config";
import { cacheService } from "#/containers/cache.container";
import { producerService } from "#/containers/producer.container";
import {
  createProducer,
  formatCacheList,
  formatCacheShow,
  runProducer,
  scanLibrary,
} from "#/services/cli-workflow.service";

const COMPLETION_SCRIPT = `#!/bin/bash
_tagwise_completions() {
  local cur prev commands producers cache_subs
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  commands="scan run cache producer completion"
  producers="renamer remix-tag remove-remix-tag"
  cache_subs="list show purge"

  if [[ \${cur} == -* ]]; then
    COMPREPLY=( $(compgen -W "--help --version" -- \${cur}) )
    return 0
  fi

  case \${COMP_CWORD} in
    1) COMPREPLY=( $(compgen -W "\${commands}" -- \${cur}) ) ;;
    2)
      case "\${COMP_WORDS[1]}" in
        run) COMPREPLY=( $(compgen -W "\${producers}" -- \${cur}) ) ;;
        scan) _tagwise_complete_folders "\${cur}" ;;
        cache) COMPREPLY=( $(compgen -W "\${cache_subs}" -- \${cur}) ) ;;
        producer) COMPREPLY=( $(compgen -W "create" -- \${cur}) ) ;;
      esac
      ;;
    3)
      case "\${COMP_WORDS[1]}" in
        run) _tagwise_complete_folders "\${cur}" ;;
        cache)
          case "\${COMP_WORDS[2]}" in
            show|purge) _tagwise_complete_folders "\${cur}" ;;
          esac
          ;;
      esac
      ;;
  esac
}

_tagwise_complete_folders() {
  local cur="$1"
  local dir
  if [[ -z "\${cur}" ]]; then
    dir="."
  else
    dir="$(dirname "\${cur}")"
  fi
  local folders=$(find "\${dir}" -maxdepth 1 -type d -name "$(basename \${cur})*" 2>/dev/null | sed "s|^\${dir}/||")
  COMPREPLY=( $(compgen -W "\${folders}" -- \${cur}) )
}

complete -F _tagwise_completions tagwise
`;

function createLinePrompt() {
  const interfaceInstance = createInterface({
    crlfDelay: Infinity,
    input: process.stdin,
  });
  const answers: string[] = [];
  const waiting: {
    reject: (error: Error) => void;
    resolve: (answer: string) => void;
  }[] = [];
  let closed = false;

  interfaceInstance.on("line", (answer) => {
    const next = waiting.shift();
    if (next) next.resolve(answer);
    else answers.push(answer);
  });
  interfaceInstance.on("close", () => {
    closed = true;
    for (const prompt of waiting.splice(0)) {
      prompt.reject(
        new Error("Input ended before all producer details were entered"),
      );
    }
  });

  return {
    close: () => interfaceInstance.close(),
    question(prompt: string): Promise<string> {
      process.stdout.write(prompt);
      const answer = answers.shift();
      if (answer !== undefined) return Promise.resolve(answer);
      if (closed) {
        return Promise.reject(
          new Error("Input ended before all producer details were entered"),
        );
      }
      return new Promise((resolve, reject) => {
        waiting.push({ reject, resolve });
      });
    },
  };
}

export function createCLI(): Command {
  const program = new Command();
  program
    .name("tagwise")
    .description("Music library tag management tool")
    .version("0.1.0");

  program
    .command("scan")
    .description("Scan a folder and cache the library")
    .argument("<folder>", "Path to the music folder")
    .action(async (folder: string) => {
      await scanLibrary(folder);
    });

  program
    .command("run")
    .description("Preview the operations generated by a producer for a library")
    .argument("<producer>")
    .argument("<folder>", "Path to the music folder")
    .action(async (producer: string, folder: string) => {
      const operations = await runProducer(folder, producer);

      console.log(`Generated ${operations.length} operation(s) for ${folder}:`);
      console.log(JSON.stringify(operations, null, 2));
    });

  const cache = program.command("cache").description("Manage cached libraries");

  cache
    .command("list")
    .description("List all cached libraries")
    .action(async () => {
      const formatted = formatCacheList(await cacheService.list());
      console.log(formatted);
    });

  cache
    .command("show")
    .description("Show details of a cached library")
    .argument("<folder>", "Path to the music folder")
    .action(async (folder: string) => {
      const result = await cacheService.show(folder);
      const formatted = formatCacheShow(result);
      console.log(formatted);
    });

  cache
    .command("purge")
    .description("Delete cached library (all or specific folder)")
    .argument("[folder]", "Path to the music folder (omit to purge all)")
    .action(async (folder?: string) => {
      await cacheService.purge(folder);

      if (folder) {
        console.log(`Purged cache for: ${folder}`);
      } else {
        console.log("Purged all cached libraries.");
      }
    });

  program
    .command("completion")
    .description("Output shell completion script")
    .action(() => {
      process.stdout.write(COMPLETION_SCRIPT);
    });

  program
    .command("producer")
    .description("Create and manage user producers")
    .command("create")
    .description("Create a typed user producer module")
    .action(async () => {
      const prompts = createLinePrompt();
      try {
        const title = (await prompts.question("Producer title: ")).trim();
        const versionInput = (
          await prompts.question("Version [1.0.0]: ")
        ).trim();
        const description = (await prompts.question("Description: ")).trim();
        if (!title) throw new Error("Producer title cannot be empty");
        if (!description) {
          throw new Error("Producer description cannot be empty");
        }

        const result = await createProducer(
          config.producersDir,
          {
            description,
            title,
            version: versionInput || "1.0.0",
          },
          producerService.getAll().map((producer) => producer.name),
        );
        console.log(`Created producer "${result.name}" at ${result.filePath}`);
      } finally {
        prompts.close();
      }
    });
  return program;
}

import { object, or } from "@optique/core/constructs";
import { message } from "@optique/core/message";
import { optional, withDefault } from "@optique/core/modifiers";
import type { InferValue } from "@optique/core/parser";
import {
  argument,
  command,
  constant,
  flag,
  option,
} from "@optique/core/primitives";
import { string } from "@optique/core/valueparser";
import { path } from "@optique/run/valueparser";
import { config } from "#/config";
import { cacheService } from "#/containers/cache.container";
import { producerService } from "#/containers/producer.container";
import {
  createProducer,
  formatCacheList,
  formatCacheShow,
  runProducer,
  scanLibrary,
} from "#/services/cli-workflow.service";

export function createCLI() {
  return or(
    object({
      command: constant("version"),
      version: flag("-v", "--version", {
        description: message`Show version information`,
      }),
    }),
    command(
      "scan",
      object({
        command: constant("scan"),
        folder: argument(path(), {
          description: message`Path to the music folder`,
        }),
      }),
      { description: message`Scan a folder and cache the library` },
    ),
    command(
      "run",
      object({
        command: constant("run"),
        folder: argument(path(), {
          description: message`Path to the music folder`,
        }),
        producer: argument(string({ metavar: "PRODUCER" })),
      }),
      {
        description: message`Preview the operations generated by a producer for a library`,
      },
    ),
    command(
      "cache",
      or(
        command("list", object({ command: constant("cache list") }), {
          description: message`List all cached libraries`,
        }),
        command(
          "show",
          object({
            command: constant("cache show"),
            folder: argument(path(), {
              description: message`Path to the music folder`,
            }),
          }),
          { description: message`Show details of a cached library` },
        ),
        command(
          "purge",
          object({
            command: constant("cache purge"),
            folder: optional(
              argument(path(), {
                description: message`Path to the music folder`,
              }),
            ),
          }),
          {
            description: message`Delete cached library (all or specific folder)`,
          },
        ),
      ),
      { description: message`Manage cached libraries` },
    ),
    command(
      "producer",
      command(
        "create",
        object({
          command: constant("producer create"),
          description: option("--description", string({ metavar: "TEXT" }), {
            description: message`Describe what the producer does`,
          }),
          producerVersion: withDefault(
            option("--producer-version", string({ metavar: "VERSION" }), {
              description: message`Producer version`,
            }),
            "1.0.0",
          ),
          title: option("--title", string({ metavar: "TITLE" }), {
            description: message`Producer title`,
          }),
        }),
        { description: message`Create a typed user producer module` },
      ),
      { description: message`Create and manage user producers` },
    ),
    optional(argument(path())),
  );
}

type CLICommand = Exclude<
  InferValue<ReturnType<typeof createCLI>>,
  string | undefined
>;

export async function executeCLICommand(invocation: CLICommand): Promise<void> {
  switch (invocation.command) {
    case "version":
      process.stdout.write("0.1.0\n");
      break;
    case "scan":
      await scanLibrary(invocation.folder);
      break;
    case "run": {
      const operations = await runProducer(
        invocation.folder,
        invocation.producer,
      );
      process.stdout.write(
        `Generated ${operations.length} operation(s) for ${invocation.folder}:\n${JSON.stringify(operations, null, 2)}\n`,
      );
      break;
    }
    case "cache list":
      process.stdout.write(`${formatCacheList(await cacheService.list())}\n`);
      break;
    case "cache show":
      process.stdout.write(
        `${formatCacheShow(await cacheService.show(invocation.folder))}\n`,
      );
      break;
    case "cache purge":
      await cacheService.purge(invocation.folder);
      process.stdout.write(
        invocation.folder
          ? `Purged cache for: ${invocation.folder}\n`
          : "Purged all cached libraries.\n",
      );
      break;
    case "producer create": {
      const result = await createProducer(
        config.producersDir,
        {
          description: invocation.description.trim(),
          title: invocation.title.trim(),
          version: invocation.producerVersion.trim() || "1.0.0",
        },
        producerService.getAll().map((producer) => producer.name),
      );
      process.stdout.write(
        `Created producer "${result.name}" at ${result.filePath}\n`,
      );
      break;
    }
  }
}
